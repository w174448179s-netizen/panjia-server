-- ============================================================================
-- 合同查询菜单图标修正
-- 背景：
--   V200009 建「合同查询」菜单时 icon 用了 'document'，但前端 svg 图标库中
--   不存在该图标（只有 documentation/form/list/clipboard 等），导致菜单
--   渲染时取不到图标、显示为空白。
-- 修复：
--   将 icon 更新为图标库中实际存在的 'clipboard'。
-- 说明：
--   已执行过的 V200005/V200009 不可修改，故新增本脚本修正存量数据；
--   同时把 2704 与 2703（旧版被跳过的空壳）一并更新，幂等。
-- ============================================================================

UPDATE sys_menu
SET icon = 'clipboard', update_time = now()
WHERE menu_id IN (1761400000000002704, 1761400000000002703)
  AND menu_name = '合同查询'
  AND (icon IS NULL OR icon IN ('', 'document'));
