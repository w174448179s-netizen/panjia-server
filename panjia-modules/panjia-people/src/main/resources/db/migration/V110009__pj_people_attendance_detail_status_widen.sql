-- ================================================================
-- 考勤每日明细：status 由 VARCHAR(64) 加宽至 VARCHAR(255)
-- 原因：钉钉《月度汇总》每日考勤结果原文可能超过 64 字符
--       （如「B班次:正常,补卡申请08-01 09:00到08-01 09:00(09:00,-)」实测 70 字符），
--       原长度导致归档事件消费写入失败（明细事务整体回滚，明细则长期 0 行）。
-- ================================================================

ALTER TABLE pj_people_attendance_detail
    ALTER COLUMN status TYPE VARCHAR(255);

COMMIT;
