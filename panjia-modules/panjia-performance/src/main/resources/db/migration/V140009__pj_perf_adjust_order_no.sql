-- ============================================================
-- 业绩调整单增加订单号列：订单号优先匹配
-- 背景：同一合同号可能挂多个订单号（跨月续签/改单），按合同号装载
-- 业绩事实会把多订单明细混排，导致「指定调整行不在该合同业绩明细中」
-- 与金额合计口径错误。调整链路改为订单号优先精确匹配，订单号为空才
-- 退化按合同号（contract_no/order_no 双键 OR）。pj_perf_adjust 落库
-- order_no 供执行端与发起校验同口径定位事实。
-- 历史调整单 order_no 为 NULL，执行端自动退化合同号旧逻辑，天然兼容。
-- ============================================================

ALTER TABLE pj_perf_adjust
    ADD COLUMN order_no varchar(64) NULL DEFAULT NULL;

COMMENT ON COLUMN pj_perf_adjust.order_no IS '订单号（同合同号多订单时订单号优先精确匹配事实；为空退化按合同号）';
