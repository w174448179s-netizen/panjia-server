-- ============================================================
-- 下线「业绩管理-期间封账」独立菜单
-- 背景：封账是算薪批次「总监锁定」节点的系统自动动作（PayrollEventListener
--      监听 PayrollLockedEvent 自动封账），手工封账与列表无实际业务场景。
-- 保留：反结账（解封）能力，入口移至「结佣明细」页（已封账行的「解封」按钮），
--      权限点 perf:period:reopen 保留，供总监/财务纠错使用（§3.5 留痕审计）。
-- ============================================================

-- 1. 删除期间封账页面菜单、期间查询、手工封账三个菜单/权限点及其角色授权
DELETE FROM sys_role_menu WHERE menu_id IN (
    1761400000000002630, -- 期间封账（页面）
    1761400000000002631, -- 期间查询
    1761400000000002632  -- 封账（手工封账）
);
DELETE FROM sys_menu WHERE menu_id IN (
    1761400000000002630,
    1761400000000002631,
    1761400000000002632
);

-- 2. 反结账权限点（F 按钮型）脱离已删除页面，挂到「业绩管理」目录下，改名「期间解封」
UPDATE sys_menu
SET parent_id = 1761400000000002200,
    menu_name = '期间解封'
WHERE menu_id = 1761400000000002633;

-- 3. 反结账权限补授总监（§3.5 解封需总监二次确认；此前仅财务持有）
INSERT INTO sys_role_menu (role_id, menu_id)
SELECT 1761300000000000010, 1761400000000002633
WHERE NOT EXISTS (
    SELECT 1 FROM sys_role_menu
    WHERE role_id = 1761300000000000010 AND menu_id = 1761400000000002633
);
