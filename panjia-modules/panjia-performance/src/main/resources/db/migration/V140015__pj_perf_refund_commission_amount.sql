-- ============================================================================
-- 退单增加「冲减结佣合计」字段
-- 背景：退单审批通过后，除负新签、负实收外，还需对已结佣部分生成负结佣明细
--       （绑定负新签事实、状态 APPROVED），保证退单月份的算薪按负值计提成。
--       该字段记录本次生成的负结佣业绩合计，供列表/详情展示与对账。
-- ============================================================================

ALTER TABLE pj_perf_refund
    ADD COLUMN IF NOT EXISTS commission_amount NUMERIC(18, 2) NOT NULL DEFAULT 0;

COMMENT ON COLUMN pj_perf_refund.commission_amount IS '冲减结佣合计（负数；已结佣部分生成的负结佣明细合计）';
